# ===================== 参数装配（唯一口径）=====================
# R132 迁入：原 diag_final_validation_v3.build_params()。任何模块要拿
# simulate_open_loop 的 params dict，都必须走这里，不得自行拼装。
def build_params(cp):
    """逐批参数覆盖 → simulate_open_loop 的 params dict。

    cp: COMBINED[b] 之类的覆盖字典（**非默认**项）。
    缺省项由 simulate/params 侧补默认值。
    """
    params = {"mux": cp["mux"], "mup": cp["mup"], "alpha_kla": cp.get("alpha_kla", 85.0),
              "PAA_c": cp.get("PAA_c", 530000.0), "N_conc_paa": 150000.0, "c_oil": 1000.0,
              "dist_flag": 1, "dist_tcin_asym": cp["dist_tcin_asym"], "m_s": cp["m_s"]}
    for k in ("m_paa", "m_s_schedule", "biomass_death_rate", "q_co2", "Y_NX", "Y_NP",
              "vis_scale", "Y_O2_X", "Y_O2_P", "m_O2_X", "mu_h_scale",
              "death_recycle",   # R131-fix: 自溶回收是一等参数，不能只在 late_death 分支透传
              # R133: 黏度分支批级覆盖（vis_k3/k1/k2/t1/t2 + 一阶松弛 vis_decay_rate）
              # R133: 黏度化验口径换算 vis_out_scale（只改上报列，不进 kla）
              "vis_k3", "vis_k1", "vis_k2", "vis_t1", "vis_t2", "vis_decay_rate",
              "vis_out_scale"):
        if k in cp:
            params[k] = cp[k]
    if "biomass_death_rate" in cp:
        params["death_start"] = cp["death_start"]
    if "late_death_rate" in cp:
        params["late_death_rate"] = cp["late_death_rate"]
        params["mu_death_ref"] = cp.get("mu_death_ref", 0.02)
        params["death_recycle"] = cp.get("death_recycle", 0.0)
    return params


def params_for(b):
    """批号 → params dict。未标定批抛 KeyError（调用方自行决定回退策略）。"""
    return build_params(COMBINED[b])


