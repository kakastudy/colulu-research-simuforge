# -*- coding: utf-8 -*-
"""Build the numerical appendix of the Supplementary Information from runs/.

Every number below is read from a frozen evidence JSON; none is transcribed
from prose.  Output: paper/supplementary_tables.md
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RUNS = os.path.join(ROOT, "runs")
OUT = os.path.join(ROOT, "paper", "supplementary_tables.md")


def load(name):
    with open(os.path.join(RUNS, name), "r", encoding="utf-8") as f:
        return json.load(f)


def fnum(x, n=4):
    try:
        return ("%." + str(n) + "f") % float(x)
    except (TypeError, ValueError):
        return str(x)


lines = ["# Supplementary tables (machine-generated)", "",
         "> Generated by `paper/make_supplement.py` from frozen artefacts in `runs/`. "
         "Numbers are not transcribed from prose.", ""]

# --- S-Table A: 86-batch frozen anchor -------------------------------------
fv = load("final_validation_v2.json")["results"]
lines += ["## S-Table A. Frozen 86-batch regression anchor", "",
          "| Batch | Type | Yield sim (g) | Yield v3 (g) | rel. error (%) | Legacy crash_level |",
          "|---:|:---|---:|---:|---:|:---|"]
for r in fv:
    lines.append("| %d | %s | %s | %s | %s | %s |" % (
        r["batch"], r.get("type", "-"), fnum(r["yield_sim"], 2), fnum(r["yield_v3"], 2),
        fnum(r["yield_err"] * 100, 4), r.get("crash_level", "-")))
errs = [r["yield_err"] * 100 for r in fv]
rmse = (sum(e * e for e in errs) / len(errs)) ** 0.5
lines += ["", "**Aggregate:** n = %d, RMSE = %s%%, within +/-5%% = %d/%d, "
          "min = %s%%, max = %s%%." % (
              len(errs), fnum(rmse, 4), sum(abs(e) <= 5 for e in errs), len(errs),
              fnum(min(errs), 4), fnum(max(errs), 4)), ""]

# --- S-Table B: channel-level nRMSE ----------------------------------------
ch = load("r157_i3_channels.json")["channels"]
lines += ["## S-Table B. Channel-level nRMSE, 86 batches, 5-fold CV", "",
          "| Channel | Kind | A median (%) | A p90 (%) | CV median (%) | CV p90 (%) | CV max (%) | Median gain (pp) |",
          "|:---|:---|---:|---:|---:|---:|---:|---:|"]
for k, v in ch.items():
    lines.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
        k, v.get("kind", "-"), fnum(v["nrmse_A_median"], 2), fnum(v["nrmse_A_p90"], 2),
        fnum(v["nrmse_cv_median"], 2), fnum(v["nrmse_cv_p90"], 2),
        fnum(v["nrmse_cv_max"], 2), fnum(v["gain_median_pp"], 2)))
lines += ["", "Interpretation: X and viscosity are deliverable; DO2 is partial; P and PAA are "
          "not identifiable; S uses a model reference and is a circular comparison.", ""]

# --- S-Table C: coverage tautology -----------------------------------------
cov = load("r160_i3_coverage_tautology.json")
lines += ["## S-Table C. Zero-information control on interval coverage", "",
          "| Channel | Junk coverage | Fitted coverage | Delta | Junk CI half-width (%) | Fitted CI half-width (%) |",
          "|:---|---:|---:|---:|---:|---:|"]
for k in cov["junk"]:
    j, r = cov["junk"][k], cov["real"][k]
    lines.append("| %s | %s | %s | %s | %s | %s |" % (
        k, fnum(j["coverage"], 12), fnum(r["coverage"], 12),
        fnum(cov["coverage_deltas"][k], 6),
        fnum(j["ci_half_width_pct"], 3), fnum(r["ci_half_width_pct"], 3)))
lines += ["", "Verdict: `%s`." % cov["verdict"], "",
          "Alternative mu +/- 1.96 sigma intervals (discriminating):", "",
          "| Channel | Junk coverage | Fitted coverage | Fitted CI half-width (%) |",
          "|:---|---:|---:|---:|"]
for k, v in cov["alt_1p96sigma"].items():
    lines.append("| %s | %s | %s | %s |" % (
        k, fnum(v["junk_coverage_mean"], 4), fnum(v["normal_coverage_mean"], 4),
        fnum(v["normal_ci_half_width_pct"], 3)))
lines.append("")

# --- S-Table D: amplitude grid ---------------------------------------------
op = load("r166_v2_optim.json")
lines += ["## S-Table D. V2 amplitude sweep (tuning seed %d)" % op["seed_main"], "",
          "| Scale | max|delta| (pp) | RMS delta (pp) | n collapse | Feasible | Distance to reference (pp) |",
          "|---:|---:|---:|---:|:---:|---:|"]
for r in sorted(op["grid"], key=lambda x: x["scale"]):
    lines.append("| %s | %s | %s | %d | %s | %s |" % (
        fnum(r["scale"], 2), fnum(r["max_abs_delta_pp"], 4), fnum(r["rms_delta_pp"], 4),
        r["n_collapse"], "yes" if r["feasible"] else "no", fnum(r["dist_to_ref_pp"], 4)))
lines += ["", "Chosen scale = %s; reference deviation = %s pp; frozen caps V2-3 = %s pp, "
          "V2-4 = %s pp; optimisation verdict = **%s** (%d/%d checks)." % (
              op["chosen_scale"], fnum(op["reference_pp"], 4), op["v23_max"], op["v24_max"],
              op["verdict"], op["n_pass"], op["n_checks"]), ""]

# --- S-Table E: seed transfer ----------------------------------------------
lines += ["## S-Table E. Out-of-sample seed transfer at the chosen scale", "",
          "| Seed | max|delta| (pp) | RMS delta (pp) | n collapse | Feasible |",
          "|---:|---:|---:|---:|:---:|"]
for r in op["seed_stage"]["per_seed"]:
    lines.append("| %d | %s | %s | %d | %s |" % (
        r["seed"], fnum(r["max_abs_delta_pp"], 4), fnum(r["rms_delta_pp"], 4),
        r["n_collapse"], "yes" if r["feasible"] else "no"))
lines += ["", "Per-batch deltas for seed 11:", "",
          "| Batch | Frozen (pp) | Injected (pp) | Delta (pp) |", "|---:|---:|---:|---:|"]
for r in op["seed_stage"]["per_seed"][0]["rows"]:
    lines.append("| %d | %s | %s | %s |" % (
        r["batch"], fnum(r["frozen_pp"], 3), fnum(r["injected_pp"], 3), fnum(r["delta_pp"], 3)))
lines.append("")

# --- S-Table F: full-amplitude injection -----------------------------------
ab = load("r166_ab_gate.json")
lines += ["## S-Table F. Full-amplitude (scale 1.0) V2 injection", "",
          "| Batch | Frozen (pp) | Injected (pp) | Delta (pp) |", "|---:|---:|---:|---:|"]
for r in ab["v2"]["full_scale_rows"]:
    lines.append("| %d | %s | %s | %s |" % (
        r["batch"], fnum(r["frozen_pp"], 3), fnum(r["injected_pp"], 3), fnum(r["delta_pp"], 3)))
lines += ["", "Catastrophic collapses: %d/%d. Gate verdict: **%s** (%d/%d checks). "
          "Only V2-3 and V2-4 remain FAIL; thresholds were never relaxed." % (
              ab["v2"]["full_scale_n_collapse"], len(ab["v2"]["full_scale_rows"]),
              ab["verdict"], ab["n_pass"], ab["n_checks"]), ""]

# --- S-Table G: eight disturbance variances --------------------------------
lines += ["## S-Table G. Eight-path disturbance variances (tau = %s h)" % op["tau_h"], "",
          "| Path | sigma |", "|:---|---:|"]
sigs = op.get("sigmas") or ab["v2"].get("sigmas") or {}
for k, v in sigs.items():
    lines.append("| %s | %s |" % (k, fnum(v, 8) if isinstance(v, (int, float)) else str(v)))
lines.append("")

# --- S-Table H: health classification --------------------------------------
acc = load("r156_acceptance.json")
s = acc["summary"]
lines += ["## S-Table H. Five-channel health classification", "",
          "| Level | Count | Batch identifiers |", "|:---|---:|:---|"]
lines.append("| normal | %d | remaining %d batches |" % (
    s["n_health"]["normal"], s["n_health"]["normal"]))
lines.append("| benign | %d | - |" % s["n_health"]["benign"])
lines.append("| degraded | %d | %s |" % (
    s["n_health"]["degraded"], ", ".join(str(b) for b in s.get("degraded_batches", []))))
lines.append("| catastrophic | %d | %s |" % (
    s["n_health"]["catastrophic"], ", ".join(str(b) for b in s.get("catastrophic_batches", []))))
lines += ["", "Legacy block retained in the same file: n_normal = %d, n_catastrophic = %d "
          "(D-38 constant classifier). Flag tallies: %s." % (
              s.get("n_normal", -1), s.get("n_catastrophic", -1),
              json.dumps(s.get("health_flags_tally", {}), ensure_ascii=False)), ""]

# --- S-Table I: gate check lists -------------------------------------------
for name, fname in [("Integration gate G1-G25", "r167_platform_gate.json"),
                    ("Final check F1-F20", "r167_final_check.json")]:
    d = load(fname)
    lines += ["## S-Table I. %s" % name, "",
              "| ID | Check | Result |", "|:---|:---|:---:|"]
    for c in d["checks"]:
        lines.append("| %s | %s | %s |" % (
            c["id"], c["name"].replace("|", "\\|"), "PASS" if c["ok"] else "FAIL"))
    lines += ["", "**Verdict: %s (%d/%d).**" % (d["verdict"], d["n_pass"], d["n_checks"]), ""]

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("WROTE", OUT, os.path.getsize(OUT), "bytes")
